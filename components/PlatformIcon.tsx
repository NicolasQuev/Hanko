function normalizeSite(site: string): string {
  const s = site.toLowerCase().trim();
  if (s.includes("crunchyroll")) return "crunchyroll";
  if (s.includes("netflix")) return "netflix";
  if (s.includes("hulu")) return "hulu";
  if (s.includes("youtube")) return "youtube";
  if (s.includes("bilibili")) return "bilibili";
  if (s.includes("hbo")) return "hbomax";
  if (s.includes("funimation")) return "funimation";
  if (s.includes("disney")) return "disneyplus";
  if (s.includes("prime")) return "primevideo";
  return "";
}

export function PlatformIcon({ site, size = 13 }: PlatformIconProps) {
  const key = normalizeSite(site);
  const spec = key ? SITES[key] : undefined;
  if (!spec) {
    return <span className="stream-chip__dot" aria-hidden="true" />;
  }
  return (
    <svg
      className="stream-chip__brand"
      viewBox={spec.viewBox}
      width={size}
      height={size}
      aria-hidden="true"
      focusable="false"
    >
      {spec.body}
    </svg>
  );
}